# A branch staff roster that is not a sign-in.
#
# users and branch_staff both require an email and a password hash, because both exist so somebody can sign in.
# Nobody from the old software arrives with a password of theirs and nobody is given a new one (owner, 30 Sep 2026),
# so filing their 138 users there would mean inventing 138 email addresses and 138 credentials for people who must
# not have any. branch_cashier_stats and branch_sales.cashier_name already say who rang what, which is the evidence
# and not the roster: it can say Ali sold Rs 40,000 on Tuesday and cannot say Ali existed, what his role was, or that
# he left in March.
#
# One table, with can_sign_in defaulting to false so nothing ever reads a row here as a credential, and role_name
# kept in their words (ADMINISTRATOR, SALE ( POS ), ACCOUNT HEAD) because theirs is what explains what somebody was
# allowed to do.
from tortoise import BaseDBAsyncClient

RUN_IN_TRANSACTION = True


async def upgrade(db: BaseDBAsyncClient) -> str:
    return """
        CREATE TABLE IF NOT EXISTS "branch_users" (
    "id" CHAR(36) NOT NULL PRIMARY KEY,
    "code" VARCHAR(40) NOT NULL,
    "name" VARCHAR(140) NOT NULL,
    "role_name" VARCHAR(120),
    "active" INT NOT NULL,
    "last_active_on" DATE,
    "can_sign_in" INT NOT NULL,
    "source" VARCHAR(10) NOT NULL,
    "received_at" TIMESTAMP NOT NULL,
    "branch_id" CHAR(36) NOT NULL REFERENCES "branches" ("id") ON DELETE CASCADE,
    CONSTRAINT "uid_branch_user_branch__da65a7" UNIQUE ("branch_id", "code")
);"""


async def downgrade(db: BaseDBAsyncClient) -> str:
    return """
        DROP TABLE IF EXISTS "branch_users";"""


