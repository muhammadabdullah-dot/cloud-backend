# An index on day for the six figure tables the Company Dashboard reads across every branch at once.
#
# Each already has a unique index starting with the branch, which serves a query that names one and cannot serve one
# that does not. With no branch chosen the dashboard filters on the day alone, so those queries scanned 1,818,232 and
# 2,251,239 rows.
#
# Measured on the Multi-Tec history, with the folds in executive_service already moved into SQL:
#     list_kpis(today)   6.46s -> 1.60s
#     list_kpis(7d)      6.40s -> 1.55s
#     list_kpis(30d)    15.69s -> 10.20s
# About three seconds to build, and a few tens of megabytes.
from tortoise import BaseDBAsyncClient

RUN_IN_TRANSACTION = True


async def upgrade(db: BaseDBAsyncClient) -> str:
    return """
        CREATE INDEX "idx_branch_cash_day_2c5b60" ON "branch_cashier_stats" ("day");
        CREATE INDEX "idx_branch_hour_day_b5aa16" ON "branch_hourly_stats" ("day");
        CREATE INDEX "idx_branch_prod_day_711d5b" ON "branch_product_cashier_stats" ("day");
        CREATE INDEX "idx_branch_prod_day_483496" ON "branch_product_stats" ("day");
        CREATE INDEX "idx_branch_retu_day_de9160" ON "branch_returns" ("day");
        CREATE INDEX "idx_branch_till_day_d01e4e" ON "branch_till_closes" ("day");"""


async def downgrade(db: BaseDBAsyncClient) -> str:
    return """
        DROP INDEX IF EXISTS "idx_branch_till_day_d01e4e";
        DROP INDEX IF EXISTS "idx_branch_retu_day_de9160";
        DROP INDEX IF EXISTS "idx_branch_prod_day_483496";
        DROP INDEX IF EXISTS "idx_branch_prod_day_711d5b";
        DROP INDEX IF EXISTS "idx_branch_hour_day_b5aa16";
        DROP INDEX IF EXISTS "idx_branch_cash_day_2c5b60";"""


